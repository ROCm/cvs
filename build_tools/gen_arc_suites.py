import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from cvs.lib import arc_lib  # noqa: E402

ARC_TESTS_DIR = os.path.join(REPO_ROOT, "cvs", "tests", "arc")
GENERATED_MARKER = "AUTO-GENERATED by build_tools/gen_arc_suites.py"
_FILE_HEADER = '''\
\'\'\'
Copyright 2025 Advanced Micro Devices, Inc.
All rights reserved. This notice is intended as a precaution against inadvertent
publication and does not imply publication or any waiver of confidentiality.
The year included in the foregoing notice is the year of creation of the work.
All code contained here is Property of Advanced Micro Devices, Inc.

{marker}
Do not edit by hand. ARC {title} suite: one ``test_<name>`` function per ARC
{unit}.

Edit the lists in cvs/lib/arc_lib.py and re-run ``make gen-arc-suites`` to
regenerate.

Run every {unit}:    cvs run {suite} ...
Run a single {unit}: cvs run {suite} test_<name> ...
List the {unit}s:    cvs list {suite}
\'\'\'

{pytest_import}from cvs.lib import arc_lib
'''
_FUNC_TEMPLATE = '''\


def test_{name}(orch, cluster_dict, config_dict, request):
    \'\'\'Run the ARC {unit} "{name}".{disruptive_doc}\'\'\'
{gate}    arc_lib.ensure_arc_ready(orch, cluster_dict, config_dict)
    arc_lib.run_arc_{unit}s(
        orch,
        cluster_dict,
        config_dict,
        ["{name}"],
        "test_{name}",
        request=request,
    )
'''


def _write(path, content):
    '''Write a generated suite.'''
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)


def _is_generated(path):
    '''Check a file before considering it for pruning.'''
    try:
        with open(path, encoding="utf-8") as fh:
            return GENERATED_MARKER in fh.read()
    except OSError:
        return False


def _prune_stale(keep):
    '''Prune only stale suites marked as generated.'''
    for name in os.listdir(ARC_TESTS_DIR):
        path = os.path.join(ARC_TESTS_DIR, name)
        if name.startswith("arc_test_") and name.endswith(".py") and name not in keep and _is_generated(path):
            os.remove(path)


def generate():
    '''Regenerate all ARC suites.'''
    keep = set()
    for suite in arc_lib.ARC_SUITES:
        key, names, unit = suite["key"], suite["names"], suite["unit"]
        filename = f"arc_test_{key}.py"
        keep.add(filename)
        header = _FILE_HEADER.format(
            marker=GENERATED_MARKER,
            title=suite["title"],
            unit=unit,
            suite=f"arc_test_{key}",
            pytest_import="import pytest\n\n" if suite["disruptive"] else "",
        )
        content = header
        for name in names:
            gate = ""
            if suite["disruptive"]:
                gate = (
                    f'    reason = arc_lib.disruptive_skip_reason(config_dict, "{name}")\n'
                    '    if reason:\n        pytest.skip(reason)\n'
                )
            content += _FUNC_TEMPLATE.format(
                name=name,
                unit=unit,
                gate=gate,
                disruptive_doc=" DISRUPTIVE: changes hardware state." if suite["disruptive"] else "",
            )
        _write(os.path.join(ARC_TESTS_DIR, filename), content)
    _prune_stale(keep)


if __name__ == "__main__":
    generate()
